/// Declarative macro for automatic implementation of `Castable` (and `CastableTo`).
/// Generally not for direct invocation, but rather used by the proc-macro `#[derive(Castable)]`.
///
/// Syntax: `<concrete struct/enum/union> => (<target traits>, ...)`
///
/// # Usage
/// ```ignore
/// make_castable_decl! {
///     SrcStruct1 => (DstTrait1, DstTrait2),
///     SrcStruct2 => (DstTrait3, DstTrait4),
/// }
/// ```
macro_rules! make_castable_decl {
    ($($source:ty => ($($target:path),* $(,)?)),+$(,)?) => {
        $(
            $(
                impl $crate::utils::traitcast::CastableTo<dyn $target> for $source {
                    const METADATA: ::std::ptr::DynMetadata<dyn $target> = {
                        let self_ptr: *const $source = ::std::ptr::null::<$source>();
                        let dyn_ptr: *const dyn $target = self_ptr as _;

                        dyn_ptr.to_raw_parts().1
                    };
                }
            )*
            // Safety:
            // All returned `CastTarget`s are valid for $source
            unsafe impl $crate::utils::traitcast::Castable for $source {
                fn casts_to(&self) -> &[$crate::utils::traitcast::CastTarget] {
                    #[allow(clippy::unused_unit)]
                    const TARGETS_LEN: usize = {
                        let a:&[()] = &[$({
                            let _: &dyn $target;
                            ()
                        },)*];
                        a.len()
                    };
                    const TARGETS: [$crate::utils::traitcast::CastTarget; TARGETS_LEN] = {
                        #[allow(unused_mut)]
                        let mut targets : [$crate::utils::traitcast::CastTarget; TARGETS_LEN] = [
                            $(
                                $crate::utils::traitcast::CastTarget::from::<$source, dyn $target>(),
                            )*
                        ];
                        targets
                    };
                    &TARGETS
                }
            }
        )+
    };
}
pub(crate) use make_castable_decl;
